// ============================================================
//  TutorialId.cs
//  튜토리얼 시나리오 식별자.
//
//  ■ 강제 진행 튜토리얼 (첫 플레이 1회)
//    첫 실행(견습 소환사로 곧장 1스테이지) → 인게임(SummonBattle) → 카드 3택·갈림길(FirstReward)
//    → (첫 환생 뒤, 보상 상자 등 팝업이 다 닫힌 메인 화면) 유물(FirstRelic) → 도감 슬라임 품질 개선(FirstCodex).
//    2스테이지부터는 플레이어를 붙잡지 않는다 (사용자 지시, 2026-09-17).
//
//    ⚠ 유물만 시점이 떨어져 있다
//      앱 첫 실행은 메인 화면을 건너뛰고 곧장 전투로 들어가므로, 유물 화면을
//      만나는 첫 순간은 '첫 환생 뒤 메인 화면' 이다. 그 전에 설명해 봤자
//      쓸 포인트가 0 이라 읽고 지나칠 수밖에 없다.
//
//  ■ 화면 하나 = 시나리오 하나
//    "전투 설명 · 스킬 사용 · 인게임 UI" 는 셋 다 인게임 화면에서
//    이어지는 이야기라 InGame 시나리오 **하나**의 스텝들이다.
//    쪼개면 중간에 끊겼을 때 이어 볼 지점이 시나리오 경계로 뭉개지고,
//    나중에 i 버튼(도움말)을 달 때도 "이 화면의 설명" 이 셋으로 흩어진다.
//    시나리오는 항상 플레이어가 보고 있는 화면 단위로 끊는다.
//
//  ■ 도움말 튜토리얼 (팝업의 i 버튼)
//    강제로 뜨지 않는다. 플레이어가 눌렀을 때만 같은 시나리오를 다시 돌린다.
//    TutorialManager.Replay() 가 완료 기록을 무시하고 재생한다.
//
//  ⚠ 번호를 재사용하지 말 것
//    TutorialData 가 이 값을 그대로 저장한다. 번호를 돌려 쓰면 옛 세이브의
//    "봤음" 기록이 엉뚱한 튜토리얼에 붙어 그 튜토리얼이 영영 안 뜬다.
//    폐기할 때는 번호를 비워 두고 주석만 남긴다.
// ============================================================

public enum TutorialId
{
    None            = 0,

    // ── 강제 진행 ───────────────────────────────────────────
    //  1~5 는 비워 둔다 — 원작 흐름(첫 인사·인게임·승리·로비·장수 스탯)을 걷어낸 자리다.
    FirstRelic      = 6,   // 첫 환생 후 메인 화면 — 유물 강화

    //  ⚠ 1~5 를 되살리지 않고 10번대에 새로 둔다 — 원작 기록과 섞이지 않게.
    SummonBattle    = 10,  // 첫 실행 1스테이지 — 인게임 UI·소환·시작 (SummonBattleTutorial)
    FirstReward     = 11,  // 1스테이지 클리어 — 카드 3택 · 갈림길 (FirstRewardTutorial)
    FirstCodex      = 12,  // 첫 환생 후 유물 다음 — 도감에서 슬라임 품질 개선 (FirstCodexTutorial)

    // ── 도움말 전용 (i 버튼) ─────────────────────────────────
    //  강제로 뜨지 않으므로 100번대로 띄워 둔다.
    //  101~104 · 107~109 는 비워 둔다 — 원작 화면(어빌리티·장비·상점·이벤트·장수·용병·분해)의 자리다.
    HelpRelic       = 100,  // 유물 · 환생
    HelpCodex       = 105,  // 도감
    HelpDifficulty  = 106,  // 난이도
    HelpMonsterDetail = 110, // 몬스터 상세 · 품질 개선 · 장비
    HelpCardSelect  = 111,  // 카드 3택
    HelpBattleInfo  = 112,  // 전황
}

public static class TutorialIdExtensions
{
    /// <summary>
    /// 조건이 맞으면 저절로 떠야 하는 튜토리얼인가.
    /// false = i 버튼으로만 열리는 도움말.
    /// </summary>
    public static bool IsForced(this TutorialId id) => id != TutorialId.None && (int)id < 100;
}
