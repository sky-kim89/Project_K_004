// ============================================================
//  Faction.cs
//  진영 배정의 단일 정의처. 어느 쪽이 아군이고 어느 쪽이 적인지는 여기서만 정한다.
//
// ============================================================
//  ⚠⚠ 이 프로젝트의 확정 규칙 ⚠⚠
//
//    인간(용사) 진영  →  TeamType.Enemy   (적)
//    몬스터 진영      →  TeamType.Ally    (아군)
//
//  원작과 정확히 반대다. 원작에서는 장수·병사가 아군이고 몬스터가 적이었다.
// ============================================================
//
//  ■ "진영" 은 신체 형태가 아니다 — 헷갈리지 말 것
//    좀비·고블린·스켈레톤은 신체가 인간형(MonsterBodyType.Humanoid)이지만
//    플레이어가 소환하는 몬스터다 → 아군이다.
//
//    갈리는 기준은 "누가 부리는가" 지 "어떻게 생겼는가" 가 아니다.
//      · 용사(Hero) 와 그 휘하 병사 → 적
//      · 소환된 몬스터 전부        → 아군
//
//  ■ 프리팹 계열별 기본 진영
//    General / Soldier 프리팹  → 용사 체계 → Enemy
//    Enemy / Elite / Boss 프리팹 → 소환 몬스터 체계 → Ally
//
//    프리팹 이름이 진영과 어긋나 보이는 건 원작 이름을 그대로 물려받았기 때문이다.
//    "Enemy.prefab" 은 이제 플레이어의 몬스터다. 이름에 속지 말 것.
//
//  ■ 왜 상수로 두나
//    TeamType.Ally / TeamType.Enemy 를 코드 곳곳에 직접 쓰면, 나중에 어느 한 곳을
//    빠뜨렸을 때 "적 휘하 병사가 아군으로 집계돼 전멸 판정이 영원히 안 서는" 식의
//    조용한 버그가 난다. 진영을 정하는 자리에서는 항상 이 상수를 쓴다.
// ============================================================

public static class Faction
{
    /// <summary>
    /// 인간(용사) 진영 = 적.
    /// General / Soldier 프리팹을 쓰는 모든 유닛이 여기 속한다.
    /// </summary>
    public const TeamType Hero = TeamType.Enemy;

    /// <summary>
    /// 몬스터 진영 = 아군.
    /// 플레이어가 소환하는 모든 몬스터 — 신체가 인간형이든 아니든 상관없다.
    /// Enemy / Elite / Boss 프리팹을 쓴다.
    /// </summary>
    public const TeamType Monster = TeamType.Ally;
}
