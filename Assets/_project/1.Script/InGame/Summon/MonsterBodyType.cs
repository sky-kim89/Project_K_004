//  몬스터의 신체 형태. 외형·장비 처리 경로가 여기서 갈린다.
//
//  ■ 이건 설계 선택이 아니라 자산 제약이다
//    PixelHeroes 의 두 자산 계열이 근본적으로 다르게 생겼다.
//
//    인간형   : Body/Head/Eyes/Ears/무기 레이어를 CharacterBuilder 가
//               런타임에 합성한다. 종족 16종 × 무기 20종 → 변형이 사실상 무한.
//               장비를 입히면 레이어가 늘어 외형이 바뀐다.
//
//    비인간형 : Bonus/Monsters 의 완성된 SpriteLibraryAsset 통짜다.
//               (Wolf / Hog / Slug / Troll)
//               레이어가 없으므로 합성도 장비 오버레이도 불가능하다.
//               1종 = 1외형. 늘리려면 원화를 새로 그려야 한다.
//
//  ■ 장비 규칙
//    인간형만 장비를 착용하고, 착용하면 외형이 바뀐다.
//    비인간형의 장비는 보류다 — 외형이 안 바뀌는 장비를 어떻게 보여 줄지
//    정해지지 않았다. 지금은 아예 못 입는다.
//
//  ■ 비인간형은 "물량" 이 아니라 "특별한 놈" 자리다
//    변형이 안 되니 떼로 소환하면 똑같이 생긴 놈이 줄줄이 나온다.
//    소수만 부리는 소환사·특성과 엮어 쓰는 것을 전제로 설계한다.
// ============================================================

public enum MonsterBodyType
{
    /// <summary>
    /// 인간형 — CharacterBuilder 로 합성한다.
    /// 좀비 · 고블린 · 스켈레톤 · 오크 등 EnemyRace 16종.
    /// 장비 착용 가능(외형 변화 포함).
    /// </summary>
    Humanoid = 0,

    /// <summary>
    /// 비인간형 — 완성된 SpriteLibraryAsset 을 그대로 쓴다.
    /// 늑대 · 멧돼지 · 슬라임 · 트롤.
    /// 장비 착용 불가 (보류).
    /// </summary>
    NonHumanoid = 1,
}
