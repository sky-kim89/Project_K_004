// ============================================================
//  MonsterDotRule.cs
//  몬스터가 거는 **지속 피해(도트)의 세기**를 정하는 단 하나의 관문.
//
//  ■ 왜 관문이 하나여야 하나
//    도트를 거는 곳이 넷이다 — 종족 패시브의 맹독 피부·화염,
//    역병 시너지의 공격 중독, 그리고 사망 시 역병 폭발.
//    보정을 각자 곱하면 넷 중 하나는 반드시 빠진다. 실제로 유물을 찍었는데
//    "독은 세지는데 화상은 그대로" 같은 상태가 되면 화면만 보고는 못 찾는다.
//
//  ■ ⚠ 거는 순간의 세기만 바꾼다
//    이미 걸려 있는 도트는 StatusEffectBufferElement 에 값이 박혀 있어
//    그대로 남는다. 그게 맞다 — 유물은 런 밖에서 정해지므로 판 도중에
//    값이 바뀔 일이 없고, 굳이 바꾸면 같은 개체가 건 도트끼리 세기가 갈린다.
//
//  ■ ⚠ 지속 시간은 건드리지 않는다
//    도트는 스택이 쌓인다(UnitStatusEffectSystem 이 버프마다 따로 틱한다).
//    시간을 늘리면 겹치는 수가 함께 늘어 세기가 제곱으로 붙는다.
//    세게 만들려면 **초당 피해**만 올린다.
// ============================================================

public static class MonsterDotRule
{
    /// <summary>
    /// 유물 보정을 얹은 초당 피해.
    ///
    /// ⚠ 도트를 만드는 곳은 반드시 이 함수를 지난다 — 지금 넷이다
    ///   (SpeciesPassiveRuntime 의 맹독 피부·화염·역병 폭발,
    ///    MonsterSynergyRuntime 의 역병 시너지).
    /// </summary>
    public static float Scale(float dps)
        => dps * (1f + RelicTreeApplier.GetSystemValue(RelicSystemEffect.DotDamageBonus));
}
