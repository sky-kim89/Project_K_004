// ============================================================
//  SummonKind.cs
//  소환 카드의 종류.
//
//  ⚠ Base(기지 소환) 는 1차 미구현이지만 값을 처음부터 넣어 둔다.
//    나중에 enum 중간/끝에 추가하면 이미 저장된 소환 덱의 정수값이
//    밀려서 세이브 마이그레이션이 필요해진다. 자리만 잡아 두는 비용이 훨씬 싸다.
// ============================================================

public enum SummonKind
{
    /// <summary>몬스터 소환 — 필드에 유닛을 남긴다. 카드 1탭 = 1마리.</summary>
    Monster = 0,

    /// <summary>스킬 소환 — 유닛을 남기지 않는 1회성/지속형 효과. (예: 파이어볼)</summary>
    Skill   = 1,

    /// <summary>기지 소환 — 필드에 지속 배치되는 고정 구조물. ❌ 1차 미구현.</summary>
    Base    = 2,
}
