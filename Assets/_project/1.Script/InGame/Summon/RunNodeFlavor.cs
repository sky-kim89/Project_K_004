using UnityEngine;

// ============================================================
//  RunNodeFlavor.cs
//  시설 화면에 깔리는 **한 토막의 이야기**.
//
//  ■ 왜 필요한가 (사용자 확정, 2026-09-06)
//    시설이 "수리 무료 / 증축 300 G" 처럼 값만 늘어놓은 목록이면, 갈림길을
//    고른 보람이 회계 장부 한 장으로 끝난다. 여기가 이 게임에서 전투가
//    멈추는 유일한 자리라, 무엇을 하는 곳인지가 **장면으로** 남아야 한다.
//
//  ■ ⚠ 규칙을 설명하지 않는다
//    "체력을 5 회복합니다" 는 선택지가 이미 말한다. 이 글이 할 일은
//    그 자리에 서 있는 느낌을 주는 것뿐이다 — 숫자를 여기 적으면 밸런스를
//    고칠 때마다 두 곳이 어긋난다 (CLAUDE.md 의 '수치는 함수에서 뽑는다').
//
//  ■ 스테이지 번호로 골라 돌려 쓴다
//    같은 시설을 런에서 두세 번 만나는데 매번 같은 글이면 두 번째부터
//    읽지 않는다. 번호를 시드로 쓰므로 재시도해도 같은 글이 나온다 —
//    편성·갈림길이 결정적인 것과 같은 규칙이다.
// ============================================================

public static class RunNodeFlavor
{
    /// <summary>제목 옆에 붙는 한 줄. 그 자리가 어떤 곳인지.</summary>
    public static string Of(RunNodeKind kind, int stageNumber)
    {
        string[] lines = LinesOf(kind);
        if (lines.Length == 0) return string.Empty;

        // 음수 나머지가 나오지 않게 절댓값을 쓴다 — 스테이지는 1부터지만
        // 부르는 쪽이 0 을 넘길 수도 있다.
        return lines[Mathf.Abs(stageNumber) % lines.Length];
    }

    static string[] LinesOf(RunNodeKind kind) => kind switch
    {
        RunNodeKind.Camp => new[]
        {
            "무너진 돌을 다시 쌓는다. 어디를 맞았는지는 손이 먼저 안다.",
            "성벽 아래에 임시 천막이 섰다. 오늘 밤은 아무도 오지 않는다.",
            "석공이 금 간 자리를 짚는다 — \"여기는 다음에 먼저 무너집니다.\"",
        },

        RunNodeKind.Forge => new[]
        {
            "화덕이 아직 식지 않았다. 쇠 대신 이름을 두드리는 곳이다.",
            "벽에 걸린 인장들이 낮게 울린다. 무엇이든 한 번은 더 깊어질 수 있다.",
            "달군 쇠에 문양을 새기면, 부르는 값이 조금 싸진다고 했다.",
        },

        RunNodeKind.Altar => new[]
        {
            "돌 위에 마른 피가 겹겹이 앉았다. 바친 것은 돌아오지 않는다 — 남는 것만 남는다.",
            "제단은 이름을 먹는다. 바친 종족의 자리가 비고, 그 자리에 표식이 남는다.",
            "아래에서 무언가 숨을 쉰다. 값을 치르면 대답이 온다.",
        },

        RunNodeKind.Shop => new[]
        {
            "떠돌이 상인이 등을 돌린 채 짐을 푼다. 파는 것은 늘 하나뿐이다.",
            "\"마력은 그릇만큼만 담깁니다.\" 상인이 병을 흔들어 보인다.",
            "골드 냄새를 맡고 온 자다. 그래도 물건은 진짜다.",
        },

        _ => new string[0],
    };
}
