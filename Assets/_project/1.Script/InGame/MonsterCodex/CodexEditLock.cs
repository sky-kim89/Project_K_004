//
//  ■ 무엇을 잠그나
//    도감이 들고 있는 것 중 **영구히 남고 전투에 곧바로 실리는 것** 둘이다.
//      · 품질 개선 (MonsterGradeUpgradeRule)
//      · 몬스터 장비 장착·해제 (MonsterGearInventory)
//    보는 것은 잠그지 않는다 — 스탯·패시브·시너지를 확인하러 여는 창이고,
//    전황(BattleInfoPopup)에서도 같은 창이 열린다.
//
//  ■ 왜 잠그나 — 이유가 둘이다
//    ① **이미 선 몬스터와 값이 갈린다.** 스탯은 소환하는 순간 한 번 굳는다
//       (MonsterStatComposer). 판 도중에 품질을 올리면 라인에 이미 서 있는
//       개체와 지금 나오는 개체가 다른 몬스터가 된다 — 화면에서는 "같은
//       카드인데 세기가 들쭉날쭉" 으로만 보인다. 장비도 마찬가지다.
//    ② **영구 재화로 이번 판을 사는 길**이 열린다. 품질 개선은 영구 골드를
//       쓴다(CLAUDE.md 골드 두 갈래). 런 중에 쓸 수 있으면 "질 것 같으면
//       창을 열어 등급을 올린다" 가 최적해가 되어, 갈림길·상점이 파는
//       런 스코프 성장이 통째로 값을 잃는다.
//
//  ■ ⚠ 판정은 여기 하나다
//    잠글 곳이 둘(품질·장비)이라 각자 LobbyManager 를 물어보게 두면,
//    흐름 상태가 늘어난 날 한쪽만 고쳐진다 — PausePopup 이 실제로 그렇게
//    깨져 있었다(LobbyManager.IsInRun 주석 참고).
// ============================================================

public static class CodexEditLock
{
    /// <summary>지금 도감을 고칠 수 없는가.</summary>
    /// <remarks>
    /// ⚠ LobbyManager 가 없으면 <b>잠그지 않는다</b> — 에디터에서 도감만 열어
    ///   확인하는 경우가 흔하다. 잠그는 쪽을 기본값으로 두면 그때 아무것도 못 한다.
    /// </remarks>
    public static bool Locked
        => LobbyManager.Instance != null && LobbyManager.Instance.IsInRun;

    /// <summary>화면에 적을 이유. 잠긴 자리마다 같은 말이어야 한다.</summary>
    public const string Reason = "런 중에는 잠긴다";
}
