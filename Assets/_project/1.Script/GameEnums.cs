// ── 팝업 타입 ─────────────────────────────────────────────────
public enum PopupType
{
    None         = 0,
    Alert        = 1,   // 확인만 있는 알림
    Confirm      = 2,   // 확인/취소
    Settings     = 3,
    // ⚠ 4 · 7~11 · 14 · 15 는 비워 둔다 — 원작 팝업(전투 결과·장비 비교·분해·
    //   어빌리티 선택/목록·용병 상점·런 상점·이벤트)을 걷어낸 자리다.
    //   당기면 이미 구운 프리팹의 _popupType 이 조용히 다른 팝업을 가리킨다.
    Pause        = 5,   // 일시 정지
    Loading      = 6,   // 로딩
    HeroDetail      = 12,  // 적(용사) 상세 — 전황에서 연다
    Reincarnation   = 13,  // 런 종료 결산 + 환생
    Codex           = 16,  // 도감 (몬스터 · 특성 · 장비)
    Relic           = 17,  // 유물 강화 (예전엔 로비 탭이었다 — RelicPopup)

    // ── 소환 반전판(v3) 신규 팝업 ─────────────────────────────
    //   ⚠ 번호를 재사용하지 말 것 — 프리팹 등록이 이 값으로 분류된다.
    CardSelect      = 18,  // 스테이지 클리어 카드 3택 (어빌리티 선택을 대체)
    BattleStats     = 19,  // 전투 통계 — 카드별 딜 기여
    // ⚠ 20 번은 비워 둔다 — RunDefeat 를 걷어낸 자리다 (2026-08-28)
    //   런 종료 결산은 원작 Reincarnation(13) 이 맡는다. 다음 값을 20 으로
    //   당기면 이미 구운 프리팹의 _popupType 이 조용히 다른 팝업을 가리킨다.
    Choice          = 21,  // 목록에서 하나 고르기 — 갈림길·특성·시설이 공유한다

    /// <summary>
    /// 몬스터 상세 — 도감에서 종족의 세부 스탯을 보고 품질을 개선한다.
    ///
    /// ⚠ HeroDetail(12) 과 다른 팝업이다
    ///   그쪽은 **적(용사)** 정보를 보는 화면으로 남는다. 장비 3칸·용병 수·
    ///   지휘력·해고처럼 몬스터에 없는 것이 절반이라, 한 화면으로 겸하면
    ///   빈 칸이 절반인 창이 된다.
    /// </summary>
    MonsterDetail   = 22,

    /// <summary>
    /// 시설 화면 — 야영지·강화소·제단·상점이 한 프리팹을 나눠 쓴다.
    ///
    /// ⚠ Choice(21) 와 다른 화면이다
    ///   그쪽은 글자 목록이고 특성 선택이 쓴다. 시설은 배경 그림과
    ///   이야기가 붙는다 (FacilityPopup 머리 주석 참고).
    /// </summary>
    Facility        = 23,

    /// <summary>강화소 — 내 카드를 격자로 펼치고 하나에 각인/증식한다.</summary>
    Forge           = 24,

    /// <summary>제단 — 내 카드를 격자로 펼치고 하나를 바친다.</summary>
    Altar           = 25,

    /// <summary>
    /// 런 종료 보상 상자 — 눌러서 흔들면 몬스터 장비 하나가 나온다.
    ///
    /// ⚠ 무엇이 나올지는 열기 **전**에 이미 정해져 인벤토리에 들어가 있다
    ///   (MonsterGearRewardRule.GrantForStage). 이 화면은 연출이다 —
    ///   연출 도중에 앱이 꺼져도 보상이 사라지지 않는다.
    /// </summary>
    GearBox         = 26,

    /// <summary>
    /// 진화·융합 갈림길 — 만렙 카드를 골랐을 때 뜬다.
    ///
    /// ⚠ 한때 HUD 자식이었다 (사용자 지적, 2026-09-07)
    ///   팝업 체계가 있는데 이것만 HUD 프리팹 안에 들어 있었다. 그 탓에
    ///   ① 겹침 순서를 손으로 맞춰야 했고(BringOverlaysToFront),
    ///   ② HUD 를 굽다 중간에 멈추면 창이 통째로 사라졌으며,
    ///   ③ 사라져도 런타임은 조용히 넘어가 "눌렀는데 아무 일도 없다" 가 됐다.
    ///   팝업은 PopupManager 가 프리팹을 따로 들고 열어 주므로 셋 다 없다.
    /// </summary>
    CardEvolve      = 27,

    /// <summary>
    /// 갈림길 상점 — 카드·특성·마력의 정수를 런 골드로 산다.
    ///
    /// ⚠ RunShop(14) 과 다른 화면이다
    ///   그쪽은 원작의 장수·장비 상점이다. 이 게임에는 플레이어의 장수가 없다.
    /// </summary>
    Shop            = 28,

    /// <summary>
    /// 전황 — 아군 진형과 적군 진형을 가운데 기준으로 나란히 본다.
    ///
    /// ⚠ 상세는 이 창 **안에서** 열린다. 팝업을 새로 쌓지 않는다.
    /// </summary>
    BattleInfo      = 29,

    /// <summary>
    /// 몬스터 장비 상세 — 레벨 트랙을 보고 레벨업·강화한다 (MonsterGearLevelRule).
    ///
    /// ⚠ 도감 장비 탭과 몬스터 상세의 장비 목록 **둘 다** 이 창을 연다
    ///   몬스터 상세 위에 겹쳐 뜬다 — 뒤에서 그 몬스터의 스탯이 보이는 편이
    ///   "이걸 끼우면 무엇이 오르나" 를 읽기 좋다.
    /// </summary>
    GearDetail      = 30,

    /// <summary>
    /// 난이도 해금 — 런 끝 보상 상자를 닫은 뒤에 뜬다 (DifficultyData.PendingUnlock).
    /// 자물쇠가 흔들리다 깨지고 새 난이도 이름이 튀어나온다.
    /// </summary>
    DifficultyUnlock = 31,
}

